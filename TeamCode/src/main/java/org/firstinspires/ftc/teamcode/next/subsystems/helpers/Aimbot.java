    private static double[] lerp(double t, double[] a, double[] b) {
        return new double[] {
            a[0] + t * (b[0] - a[0]),
            a[1] + t * (b[1] - a[1])
        };
    }

    public static double[] get(double distance) {
        double d = distance - DIST_MIN;
        int n = LUT.length;

        if (d <= 0) return LUT[0];
        if (d >= (n - 1) * STEP) return LUT[n - 1];

        int i = (int)Math.floor(d / STEP);
        double t = (d - i * STEP) / STEP;

        return lerp(t, LUT[i], LUT[i + 1]);
    }

