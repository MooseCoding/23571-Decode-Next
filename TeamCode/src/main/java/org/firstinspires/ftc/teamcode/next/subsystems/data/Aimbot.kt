        fun lerp(t:Double, low: DoubleArray, high: DoubleArray):DoubleArray {
            val hood = low[0] + t*(high[0] - low[0])
            val flywheel = low[1]+t*(high[1]-low[1])
            return doubleArrayOf(hood, flywheel)
        }

